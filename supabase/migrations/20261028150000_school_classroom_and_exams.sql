create table if not exists public.school_classroom_posts (
  id bigint generated by default as identity primary key,
  school_id bigint not null references public.schools (id) on delete cascade,
  class_id bigint not null,
  subject_id bigint,
  author_id bigint not null,
  post_type varchar(16) not null
    check (post_type in ('lesson', 'assignment', 'notice', 'material', 'live_class')),
  title varchar(160) not null,
  content_body text not null default '',
  deadline date,
  meeting_url text,
  attachment_path text,
  attachment_name varchar(160),
  created_at timestamptz not null default now(),
  constraint classroom_post_class_school_fk
    foreign key (class_id, school_id)
    references public.school_classes (id, school_id) on delete cascade,
  constraint classroom_post_subject_school_fk
    foreign key (subject_id, school_id)
    references public.school_subjects (id, school_id) on delete set null (subject_id),
  constraint classroom_post_author_school_fk
    foreign key (author_id, school_id)
    references public.enrollments (id, school_id) on delete cascade
);

create index if not exists school_classroom_posts_class_created
  on public.school_classroom_posts (school_id, class_id, created_at desc);

create table if not exists public.school_portal_exams (
  id bigint generated by default as identity primary key,
  school_id bigint not null references public.schools (id) on delete cascade,
  class_id bigint not null,
  subject_id bigint,
  academic_term_id bigint not null,
  teacher_id bigint not null,
  title varchar(160) not null,
  questions jsonb not null check (jsonb_typeof(questions) = 'array'),
  duration_minutes integer not null check (duration_minutes between 1 and 240),
  attempts_allowed smallint not null default 1 check (attempts_allowed between 1 and 5),
  is_published boolean not null default true,
  created_at timestamptz not null default now(),
  expires_at timestamptz not null,
  constraint portal_exam_class_school_fk
    foreign key (class_id, school_id)
    references public.school_classes (id, school_id) on delete cascade,
  constraint portal_exam_subject_school_fk
    foreign key (subject_id, school_id)
    references public.school_subjects (id, school_id) on delete set null (subject_id),
  constraint portal_exam_term_school_fk
    foreign key (academic_term_id, school_id)
    references public.academic_terms (id, school_id) on delete cascade,
  constraint portal_exam_teacher_school_fk
    foreign key (teacher_id, school_id)
    references public.enrollments (id, school_id) on delete cascade,
  constraint portal_exam_id_school_unique unique (id, school_id)
);

create index if not exists school_portal_exams_class_created
  on public.school_portal_exams (school_id, class_id, created_at desc);

create table if not exists public.school_portal_exam_attempts (
  id bigint generated by default as identity primary key,
  school_id bigint not null references public.schools (id) on delete cascade,
  exam_id bigint not null,
  student_id bigint not null,
  attempt_number smallint not null check (attempt_number between 1 and 5),
  start_time timestamptz not null default now(),
  end_time timestamptz,
  answers jsonb not null default '[]'::jsonb check (jsonb_typeof(answers) = 'array'),
  score integer check (score is null or score >= 0),
  status varchar(12) not null default 'started'
    check (status in ('started', 'submitted', 'expired', 'revoked')),
  submission_type varchar(12) not null default 'manual'
    check (submission_type in ('manual', 'timed_out')),
  constraint portal_attempt_exam_school_fk
    foreign key (exam_id, school_id)
    references public.school_portal_exams (id, school_id) on delete cascade,
  constraint portal_attempt_student_school_fk
    foreign key (student_id, school_id)
    references public.enrollments (id, school_id) on delete cascade,
  constraint portal_attempt_once_per_number
    unique (school_id, exam_id, student_id, attempt_number)
);

create index if not exists school_portal_exam_attempts_student
  on public.school_portal_exam_attempts (school_id, student_id, exam_id);

