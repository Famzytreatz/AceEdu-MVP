create or replace function public.start_school_portal_exam(
  target_school_id bigint,
  target_exam_id bigint,
  target_student_id bigint
)
returns bigint
language plpgsql
security definer
set search_path = public
as $$
declare
  exam_row public.school_portal_exams%rowtype;
  student_class_id bigint;
  attempt_count integer;
  new_attempt_id bigint;
begin
  select * into exam_row
  from public.school_portal_exams
  where school_id = target_school_id and id = target_exam_id
  for update;
  if not found or not exam_row.is_published then
    raise exception 'Exam is unavailable.' using errcode = '22023';
  end if;

  select class_id into student_class_id
  from public.enrollments
  where id = target_student_id and school_id = target_school_id
    and role = 'student' and status = 'Active';
  if not found or student_class_id <> exam_row.class_id then
    raise exception 'Exam is not assigned to this student.' using errcode = '42501';
  end if;

  select id into new_attempt_id
  from public.school_portal_exam_attempts
  where school_id = target_school_id and exam_id = target_exam_id
    and student_id = target_student_id and status = 'started'
  order by attempt_number desc
  limit 1
  for update;
  if found then
    return new_attempt_id;
  end if;

  if exam_row.expires_at <= now() then
    raise exception 'Exam is unavailable.' using errcode = '22023';
  end if;

  select count(*) into attempt_count
  from public.school_portal_exam_attempts
  where school_id = target_school_id and exam_id = target_exam_id
    and student_id = target_student_id;
  if attempt_count >= exam_row.attempts_allowed then
    raise exception 'No attempts remain for this exam.' using errcode = '22023';
  end if;

  insert into public.school_portal_exam_attempts (
    school_id, exam_id, student_id, attempt_number
  )
  values (
    target_school_id, target_exam_id, target_student_id, attempt_count + 1
  )
  returning id into new_attempt_id;
  return new_attempt_id;
end;
$$;

create or replace function public.save_school_portal_exam_draft(
  target_school_id bigint,
  target_exam_id bigint,
  target_attempt_id bigint,
  target_student_id bigint,
  submitted_answers jsonb
)
returns boolean
language plpgsql
security definer
set search_path = public
as $$
declare
  exam_row public.school_portal_exams%rowtype;
  attempt_row public.school_portal_exam_attempts%rowtype;
  student_class_id bigint;
  answer_row jsonb;
  question_index integer;
  selected_index integer;
  question_total integer;
begin
  if jsonb_typeof(submitted_answers) <> 'array' then
    raise exception 'Exam answers are invalid.' using errcode = '22023';
  end if;

  select * into exam_row
  from public.school_portal_exams
  where school_id = target_school_id and id = target_exam_id;
  if not found then
    raise exception 'Exam not found.' using errcode = 'P0002';
  end if;

  select * into attempt_row
  from public.school_portal_exam_attempts
  where school_id = target_school_id and exam_id = target_exam_id
    and id = target_attempt_id and student_id = target_student_id
  for update;
  if not found or attempt_row.status <> 'started' then
    raise exception 'Exam attempt is not active.' using errcode = '22023';
  end if;

  select class_id into student_class_id
  from public.enrollments
  where id = target_student_id and school_id = target_school_id
    and role = 'student' and status = 'Active';
  if not found or student_class_id <> exam_row.class_id then
    raise exception 'Exam is not assigned to this student.' using errcode = '42501';
  end if;

  if now() > attempt_row.start_time + make_interval(mins => exam_row.duration_minutes) then
    raise exception 'The exam time limit has elapsed.' using errcode = '22023';
  end if;

  question_total := jsonb_array_length(exam_row.questions);
  if jsonb_array_length(submitted_answers) > question_total then
    raise exception 'Exam submission contains too many answers.' using errcode = '22023';
  end if;
  if exists (
    select 1
    from jsonb_array_elements(submitted_answers) as answer_values(answer)
    group by answer ->> 'questionIndex'
    having count(*) > 1
  ) then
    raise exception 'Exam answers cannot repeat a question.' using errcode = '22023';
  end if;

  for answer_row in select value from jsonb_array_elements(submitted_answers)
  loop
    if jsonb_typeof(answer_row) <> 'object'
       or coalesce(answer_row ->> 'questionIndex', '') !~ '^(0|[1-9][0-9]?)$'
       or coalesce(answer_row ->> 'selectedOptionIndex', '') !~ '^[0-3]$' then
      raise exception 'Exam answer is invalid.' using errcode = '22023';
    end if;
    question_index := (answer_row ->> 'questionIndex')::integer;
    selected_index := (answer_row ->> 'selectedOptionIndex')::integer;
    if question_index >= question_total or selected_index > 3 then
      raise exception 'Exam answer is invalid.' using errcode = '22023';
    end if;
  end loop;

  update public.school_portal_exam_attempts
  set answers = submitted_answers
  where id = target_attempt_id and school_id = target_school_id
    and student_id = target_student_id and status = 'started';
  if not found then
    raise exception 'Exam attempt is no longer active.' using errcode = '22023';
  end if;
  return true;
end;
$$;

create or replace function public.submit_school_portal_exam(
  target_school_id bigint,
  target_exam_id bigint,
  target_attempt_id bigint,
  target_student_id bigint,
  submitted_answers jsonb,
  submission_kind varchar default 'manual'
)
returns integer
language plpgsql
security definer
set search_path = public
as $$
declare
  exam_row public.school_portal_exams%rowtype;
  attempt_row public.school_portal_exam_attempts%rowtype;
  answer_row jsonb;
  question_index integer;
  selected_index integer;
  computed_score integer := 0;
  question_total integer;
begin
  if jsonb_typeof(submitted_answers) <> 'array'
     or submission_kind not in ('manual', 'timed_out') then
    raise exception 'Exam submission is invalid.' using errcode = '22023';
  end if;

  select * into exam_row
  from public.school_portal_exams
  where school_id = target_school_id and id = target_exam_id;
  if not found then
    raise exception 'Exam not found.' using errcode = 'P0002';
  end if;

  select * into attempt_row
  from public.school_portal_exam_attempts
  where school_id = target_school_id and exam_id = target_exam_id
    and id = target_attempt_id and student_id = target_student_id
  for update;
  if not found or attempt_row.status <> 'started' then
    raise exception 'Exam attempt is not active.' using errcode = '22023';
  end if;

  if now() > attempt_row.start_time + make_interval(mins => exam_row.duration_minutes)
     and submission_kind <> 'timed_out' then
    raise exception 'The exam time limit has elapsed.' using errcode = '22023';
  end if;
  if now() <= attempt_row.start_time + make_interval(mins => exam_row.duration_minutes)
     and submission_kind = 'timed_out' then
    raise exception 'The exam time limit has not elapsed.' using errcode = '22023';
  end if;

  question_total := jsonb_array_length(exam_row.questions);
  if jsonb_array_length(submitted_answers) > question_total then
    raise exception 'Exam submission contains too many answers.' using errcode = '22023';
  end if;

  for answer_row in select value from jsonb_array_elements(submitted_answers)
  loop
    question_index := (answer_row ->> 'questionIndex')::integer;
    selected_index := (answer_row ->> 'selectedOptionIndex')::integer;
    if question_index < 0 or question_index >= question_total
       or selected_index < 0 or selected_index > 3 then
      raise exception 'Exam answer is invalid.' using errcode = '22023';
    end if;
    if (exam_row.questions -> question_index ->> 'correctAnswerIndex')::integer = selected_index then
      computed_score := computed_score + 1;
    end if;
  end loop;

  update public.school_portal_exam_attempts
  set answers = submitted_answers,
      score = computed_score,
      end_time = now(),
      status = 'submitted',
      submission_type = submission_kind
  where id = target_attempt_id
    and school_id = target_school_id
    and exam_id = target_exam_id
    and student_id = target_student_id
    and status = 'started';
  if not found then
    raise exception 'Exam attempt is no longer active.' using errcode = '22023';
  end if;
  return computed_score;
end;
$$;

