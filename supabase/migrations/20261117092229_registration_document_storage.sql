-- Private storage and metadata for school registration reference documents.
insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
values (
  'aceedu-registration-documents',
  'aceedu-registration-documents',
  false,
  15728640,
  array['application/pdf', 'image/jpeg', 'image/png', 'image/webp']
)
on conflict (id) do update
set
  name = excluded.name,
  public = false,
  file_size_limit = excluded.file_size_limit,
  allowed_mime_types = excluded.allowed_mime_types;

create table if not exists public.school_registration_documents (
  id bigint generated by default as identity primary key,
  school_id bigint not null,
  form_id bigint not null,
  storage_path text not null unique,
  original_filename varchar(255) not null,
  mime_type varchar(100) not null,
  file_size_bytes bigint,
  upload_status varchar(20) not null default 'pending',
  analysis_status varchar(20) not null default 'not_started',
  uploaded_at timestamptz,
  expires_at timestamptz not null default (now() + interval '2 hours'),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint school_registration_documents_form_school_fk
    foreign key (form_id, school_id)
    references public.school_registration_forms (id, school_id)
    on delete cascade,
  constraint school_registration_documents_mime_type_check
    check (mime_type in ('application/pdf', 'image/jpeg', 'image/png', 'image/webp')),
  constraint school_registration_documents_size_check
    check (file_size_bytes is null or file_size_bytes between 1 and 15728640),
  constraint school_registration_documents_upload_status_check
    check (upload_status in ('pending', 'uploaded', 'failed', 'deleted')),
  constraint school_registration_documents_analysis_status_check
    check (analysis_status in ('not_started', 'queued', 'processing', 'completed', 'failed'))
);

create index if not exists school_registration_documents_school_form_idx
  on public.school_registration_documents (school_id, form_id, created_at desc);

alter table public.school_registration_documents enable row level security;
revoke all on public.school_registration_documents from public, anon, authenticated;
grant all on public.school_registration_documents to service_role;
grant usage, select on sequence public.school_registration_documents_id_seq to service_role;

create or replace function public.enforce_registration_document_limit()
returns trigger
language plpgsql
security invoker
set search_path = public, pg_temp
as $$
declare
  active_document_count integer;
begin
  perform 1
  from public.school_registration_forms
  where id = new.form_id
    and school_id = new.school_id
    and is_active = true
  for update;

  if not found then
    raise exception 'Registration form not found or inactive.'
      using errcode = 'P0002';
  end if;

  select count(*)
  into active_document_count
  from public.school_registration_documents
  where school_id = new.school_id
    and form_id = new.form_id
    and (
      upload_status = 'uploaded'
      or (upload_status = 'pending' and expires_at > now())
    );

  if active_document_count >= 5 then
    raise exception 'A registration form can have no more than 5 uploaded or pending documents.'
      using errcode = '22023';
  end if;

  return new;
end;
$$;

drop trigger if exists school_registration_documents_limit_trigger
  on public.school_registration_documents;

create trigger school_registration_documents_limit_trigger
before insert on public.school_registration_documents
for each row
execute function public.enforce_registration_document_limit();

revoke all on function public.enforce_registration_document_limit() from public, anon, authenticated;
