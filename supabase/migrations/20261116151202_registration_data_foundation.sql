-- AceEdu registration data foundation
-- Adds school-scoped registration forms, immutable-version-ready form definitions,
-- pending submissions, review events, and custom student field storage.
-- Existing public.enrollments records are not modified.

create table public.school_registration_forms (
  id bigint generated by default as identity primary key,
  school_id bigint not null references public.schools(id) on delete cascade,
  form_key varchar(80) not null check (form_key ~ '^[a-z][a-z0-9_-]{1,79}$'),
  form_name varchar(160) not null,
  description text,
  form_purpose varchar(40) not null default 'student_admission' check (form_purpose in ('student_admission')),
  is_default boolean not null default false,
  is_active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint school_registration_forms_school_key_unique unique (school_id, form_key),
  constraint school_registration_forms_id_school_unique unique (id, school_id)
);

create unique index school_registration_forms_one_default_idx
  on public.school_registration_forms (school_id)
  where is_default = true and is_active = true;

create index school_registration_forms_school_active_idx
  on public.school_registration_forms (school_id, is_active, created_at desc);

create table public.school_registration_form_versions (
  id bigint generated by default as identity primary key,
  school_id bigint not null references public.schools(id) on delete cascade,
  form_id bigint not null,
  version_number integer not null check (version_number > 0),
  schema_version integer not null default 1 check (schema_version > 0),
  status varchar(16) not null default 'draft' check (status in ('draft', 'published', 'retired')),
  form_definition jsonb not null default '{"sections":[],"fields":[]}'::jsonb
    check (jsonb_typeof(form_definition) = 'object' and pg_column_size(form_definition) <= 262144),
  published_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint school_registration_form_versions_form_school_fk
    foreign key (form_id, school_id) references public.school_registration_forms(id, school_id) on delete cascade,
  constraint school_registration_form_versions_number_unique unique (form_id, version_number),
  constraint school_registration_form_versions_id_school_unique unique (id, school_id),
  constraint school_registration_form_versions_id_school_form_unique unique (id, school_id, form_id),
  constraint school_registration_form_versions_publish_time_check
    check ((status = 'published' and published_at is not null) or status <> 'published')
);

create unique index school_registration_one_published_version_idx
  on public.school_registration_form_versions (form_id)
  where status = 'published';

create index school_registration_form_versions_school_form_idx
  on public.school_registration_form_versions (school_id, form_id, version_number desc);

create table public.school_student_custom_fields (
  id bigint generated by default as identity primary key,
  school_id bigint not null references public.schools(id) on delete cascade,
  field_key varchar(100) not null check (field_key ~ '^[a-z][a-z0-9_]{0,99}$'),
  field_label varchar(160) not null,
  field_type varchar(20) not null check (
    field_type in ('text', 'textarea', 'email', 'phone', 'date', 'number', 'boolean', 'select', 'multiselect', 'radio', 'checkbox', 'file')
  ),
  description text,
  options jsonb not null default '[]'::jsonb check (jsonb_typeof(options) = 'array'),
  validation_rules jsonb not null default '{}'::jsonb check (jsonb_typeof(validation_rules) = 'object'),
  data_classification varchar(16) not null default 'standard'
    check (data_classification in ('standard', 'sensitive', 'restricted')),
  is_active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint school_student_custom_fields_key_unique unique (school_id, field_key),
  constraint school_student_custom_fields_id_school_unique unique (id, school_id)
);

create index school_student_custom_fields_school_active_idx
  on public.school_student_custom_fields (school_id, is_active, field_label);

create table public.school_registration_submissions (
  id bigint generated by default as identity primary key,
  school_id bigint not null references public.schools(id) on delete cascade,
  form_id bigint not null,
  form_version_id bigint not null,
  status varchar(24) not null default 'draft' check (
    status in ('draft', 'submitted', 'under_review', 'changes_requested', 'approved', 'rejected', 'withdrawn')
  ),
  source varchar(24) not null default 'staff_entry' check (
    source in ('parent_online', 'staff_entry', 'completed_form_scan', 'bulk_import')
  ),
  response_data jsonb not null default '{}'::jsonb
    check (jsonb_typeof(response_data) = 'object' and pg_column_size(response_data) <= 1048576),
  student_id bigint,
  created_by_enrollment_id bigint,
  reviewed_by_enrollment_id bigint,
  review_notes text,
  submitted_at timestamptz,
  reviewed_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint school_registration_submissions_form_school_fk
    foreign key (form_id, school_id) references public.school_registration_forms(id, school_id) on delete restrict,
  constraint school_registration_submissions_version_form_fk
    foreign key (form_version_id, school_id, form_id)
    references public.school_registration_form_versions(id, school_id, form_id) on delete restrict,
  constraint school_registration_submissions_student_school_fk
    foreign key (student_id, school_id) references public.enrollments(id, school_id) on delete set null (student_id),
  constraint school_registration_submissions_creator_school_fk
    foreign key (created_by_enrollment_id, school_id) references public.enrollments(id, school_id) on delete set null (created_by_enrollment_id),
  constraint school_registration_submissions_reviewer_school_fk
    foreign key (reviewed_by_enrollment_id, school_id) references public.enrollments(id, school_id) on delete set null (reviewed_by_enrollment_id),
  constraint school_registration_submissions_approved_student_check check (status <> 'approved' or student_id is not null),
  constraint school_registration_submissions_id_school_unique unique (id, school_id)
);

create index school_registration_submissions_queue_idx
  on public.school_registration_submissions (school_id, status, created_at desc);

create index school_registration_submissions_student_idx
  on public.school_registration_submissions (school_id, student_id) where student_id is not null;

create index school_registration_submissions_form_idx
  on public.school_registration_submissions (school_id, form_id, created_at desc);

create table public.school_registration_submission_events (
  id bigint generated by default as identity primary key,
  school_id bigint not null references public.schools(id) on delete cascade,
  submission_id bigint not null,
  actor_enrollment_id bigint,
  event_type varchar(32) not null check (
    event_type in (
      'created', 'submitted', 'review_started', 'changes_requested', 'approved', 'rejected',
      'withdrawn', 'response_updated', 'document_added', 'ai_extraction_completed',
      'ai_extraction_failed', 'field_corrected'
    )
  ),
  event_data jsonb not null default '{}'::jsonb check (jsonb_typeof(event_data) = 'object'),
  created_at timestamptz not null default now(),
  constraint school_registration_submission_events_submission_fk
    foreign key (submission_id, school_id)
    references public.school_registration_submissions(id, school_id) on delete cascade,
  constraint school_registration_submission_events_actor_fk
    foreign key (actor_enrollment_id, school_id)
    references public.enrollments(id, school_id) on delete set null (actor_enrollment_id)
);

create index school_registration_submission_events_timeline_idx
  on public.school_registration_submission_events (school_id, submission_id, created_at);

create table public.school_student_custom_field_values (
  id bigint generated by default as identity primary key,
  school_id bigint not null references public.schools(id) on delete cascade,
  student_id bigint not null,
  custom_field_id bigint not null,
  value jsonb not null check (jsonb_typeof(value) <> 'null' and pg_column_size(value) <= 65536),
  source_submission_id bigint,
  captured_in_form_version_id bigint,
  updated_by_enrollment_id bigint,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint school_student_custom_field_values_student_fk
    foreign key (student_id, school_id) references public.enrollments(id, school_id) on delete cascade,
  constraint school_student_custom_field_values_definition_fk
    foreign key (custom_field_id, school_id) references public.school_student_custom_fields(id, school_id) on delete restrict,
  constraint school_student_custom_field_values_submission_fk
    foreign key (source_submission_id, school_id)
    references public.school_registration_submissions(id, school_id) on delete set null (source_submission_id),
  constraint school_student_custom_field_values_version_fk
    foreign key (captured_in_form_version_id, school_id)
    references public.school_registration_form_versions(id, school_id) on delete set null (captured_in_form_version_id),
  constraint school_student_custom_field_values_editor_fk
    foreign key (updated_by_enrollment_id, school_id)
    references public.enrollments(id, school_id) on delete set null (updated_by_enrollment_id),
  constraint school_student_custom_field_values_once_per_field unique (school_id, student_id, custom_field_id)
);

create index school_student_custom_field_values_field_idx
  on public.school_student_custom_field_values (school_id, custom_field_id);

create index school_student_custom_field_values_student_idx
  on public.school_student_custom_field_values (school_id, student_id);

alter table public.school_registration_forms enable row level security;
alter table public.school_registration_form_versions enable row level security;
alter table public.school_student_custom_fields enable row level security;
alter table public.school_registration_submissions enable row level security;
alter table public.school_registration_submission_events enable row level security;
