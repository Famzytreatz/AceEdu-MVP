create or replace function public.submit_student_subject_request(
  target_school_id bigint,
  target_student_id bigint,
  selected_subject_ids bigint[]
)
returns bigint
language plpgsql
security invoker
set search_path = public
as $$
declare
  target_class_level_id bigint;
  minimum_count smallint;
  maximum_count smallint;
  selected_count integer;
  valid_count integer;
  compulsory_count integer;
  pending_request_id bigint;
begin
  select class_level_id into target_class_level_id
  from public.enrollments
  where id = target_student_id
    and school_id = target_school_id
    and role = 'student'
    and status = 'Active';

  if target_class_level_id is null then
    raise exception 'An active student class assignment is required.'
      using errcode = '22023';
  end if;

  if selected_subject_ids is null
    or cardinality(selected_subject_ids) > 50
    or cardinality(selected_subject_ids) <> (
      select count(distinct subject_id)
      from unnest(selected_subject_ids) as selected(subject_id)
    ) then
    raise exception 'Select a valid subject combination.'
      using errcode = '22023';
  end if;

  select minimum_subjects, maximum_subjects
  into minimum_count, maximum_count
  from public.school_class_subject_rules
  where school_id = target_school_id
    and class_level_id = target_class_level_id;
  minimum_count := coalesce(minimum_count, 1);
  maximum_count := coalesce(maximum_count, 15);
  selected_count := cardinality(selected_subject_ids);

  if selected_count < minimum_count or selected_count > maximum_count then
    raise exception 'Choose between % and % subjects.', minimum_count, maximum_count
      using errcode = '22023';
  end if;

  select count(*) into valid_count
  from public.school_subject_options
  where school_id = target_school_id
    and class_level_id = target_class_level_id
    and is_active
    and id = any(selected_subject_ids);

  if valid_count <> selected_count then
    raise exception 'One or more selected subjects are not available for your class.'
      using errcode = '22023';
  end if;

  select count(*) into compulsory_count
  from public.school_subject_options
  where school_id = target_school_id
    and class_level_id = target_class_level_id
    and is_active
    and is_compulsory
    and not (id = any(selected_subject_ids));

  if compulsory_count > 0 then
    raise exception 'Include every compulsory subject in your selection.'
      using errcode = '22023';
  end if;

  select id into pending_request_id
  from public.student_subject_requests
  where school_id = target_school_id
    and student_id = target_student_id
    and status = 'pending'
  for update;

  if pending_request_id is null then
    insert into public.student_subject_requests
      (school_id, student_id, class_level_id)
    values
      (target_school_id, target_student_id, target_class_level_id)
    returning id into pending_request_id;
  else
    update public.student_subject_requests
    set class_level_id = target_class_level_id,
        submitted_at = now()
    where id = pending_request_id;
    delete from public.student_subject_request_items
    where school_id = target_school_id
      and request_id = pending_request_id;
  end if;

  insert into public.student_subject_request_items
    (school_id, request_id, class_level_id, subject_id)
  select target_school_id, pending_request_id, target_class_level_id, subject_id
  from unnest(selected_subject_ids) as selected(subject_id);

  return pending_request_id;
end;
$$;

create or replace function public.review_student_subject_request(
  target_school_id bigint,
  target_request_id bigint,
  review_decision text
)
returns boolean
language plpgsql
security invoker
set search_path = public
as $$
declare
  target_student_id bigint;
  target_class_level_id bigint;
  minimum_count smallint;
  maximum_count smallint;
  selected_count integer;
begin
  if review_decision not in ('approved', 'declined') then
    raise exception 'Choose approve or decline.'
      using errcode = '22023';
  end if;

  select student_id, class_level_id
  into target_student_id, target_class_level_id
  from public.student_subject_requests
  where id = target_request_id
    and school_id = target_school_id
    and status = 'pending'
  for update;

  if target_student_id is null then
    return false;
  end if;

  if review_decision = 'approved' then
    select minimum_subjects, maximum_subjects
    into minimum_count, maximum_count
    from public.school_class_subject_rules
    where school_id = target_school_id
      and class_level_id = target_class_level_id;
    minimum_count := coalesce(minimum_count, 1);
    maximum_count := coalesce(maximum_count, 15);

    select count(*) into selected_count
    from public.student_subject_request_items
    where school_id = target_school_id
      and request_id = target_request_id;
    if selected_count < minimum_count or selected_count > maximum_count then
      raise exception 'This request no longer meets the class subject limits. Ask the student to submit a new combination.'
        using errcode = '22023';
    end if;

    if exists (
      select 1
      from public.school_subject_options subject_option
      where subject_option.school_id = target_school_id
        and subject_option.class_level_id = target_class_level_id
        and subject_option.is_active
        and subject_option.is_compulsory
        and not exists (
          select 1
          from public.student_subject_request_items item
          where item.school_id = target_school_id
            and item.request_id = target_request_id
            and item.subject_id = subject_option.id
        )
    ) or exists (
      select 1
      from public.student_subject_request_items item
      join public.school_subject_options subject_option
        on subject_option.id = item.subject_id
        and subject_option.school_id = item.school_id
        and subject_option.class_level_id = item.class_level_id
      where item.school_id = target_school_id
        and item.request_id = target_request_id
        and not subject_option.is_active
    ) then
      raise exception 'This request no longer matches the active compulsory subjects. Ask the student to submit a new combination.'
        using errcode = '22023';
    end if;

    update public.student_subject_requests
    set is_current = false
    where school_id = target_school_id
      and student_id = target_student_id
      and is_current;
  end if;

  update public.student_subject_requests
  set status = review_decision,
      is_current = review_decision = 'approved',
      reviewed_at = now()
  where id = target_request_id
    and school_id = target_school_id;

  return true;
end;
$$;

