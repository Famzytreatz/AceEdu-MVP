create table if not exists public.school_class_subject_rules (
  school_id bigint not null references public.schools (id) on delete cascade,
  class_level_id bigint not null,
  minimum_subjects smallint not null default 1 check (minimum_subjects between 0 and 50),
  maximum_subjects smallint not null default 15 check (maximum_subjects between 1 and 50),
  updated_at timestamptz not null default now(),
  primary key (school_id, class_level_id),
  constraint school_class_subject_rule_range check (minimum_subjects <= maximum_subjects),
  constraint school_class_subject_rule_level_fk
    foreign key (class_level_id, school_id)
    references public.school_class_levels (id, school_id) on delete cascade
);

create table if not exists public.school_subject_options (
  id bigint generated by default as identity primary key,
  school_id bigint not null references public.schools (id) on delete cascade,
  class_level_id bigint not null,
  name varchar(100) not null,
  is_compulsory boolean not null default false,
  is_active boolean not null default true,
  created_at timestamptz not null default now(),
  constraint school_subject_option_name_unique unique (school_id, class_level_id, name),
  constraint school_subject_option_id_level_school_unique unique (id, class_level_id, school_id),
  constraint school_subject_option_level_fk
    foreign key (class_level_id, school_id)
    references public.school_class_levels (id, school_id) on delete cascade
);

create table if not exists public.student_subject_requests (
  id bigint generated by default as identity primary key,
  school_id bigint not null references public.schools (id) on delete cascade,
  student_id bigint not null,
  class_level_id bigint not null,
  status varchar(12) not null default 'pending'
    check (status in ('pending', 'approved', 'declined')),
  is_current boolean not null default false,
  submitted_at timestamptz not null default now(),
  reviewed_at timestamptz,
  constraint student_subject_request_id_school_unique unique (id, school_id),
  constraint student_subject_request_student_fk
    foreign key (student_id, school_id)
    references public.enrollments (id, school_id) on delete cascade,
  constraint student_subject_request_class_fk
    foreign key (class_level_id, school_id)
    references public.school_class_levels (id, school_id)
);

create unique index if not exists one_pending_subject_request_per_student
