create table if not exists public.student_subject_request_items (
  school_id bigint not null references public.schools (id) on delete cascade,
  request_id bigint not null,
  class_level_id bigint not null,
  subject_id bigint not null,
  primary key (request_id, subject_id),
  constraint student_subject_request_item_request_fk
    foreign key (request_id, school_id)
    references public.student_subject_requests (id, school_id) on delete cascade,
  constraint student_subject_request_item_subject_fk
    foreign key (subject_id, class_level_id, school_id)
    references public.school_subject_options (id, class_level_id, school_id) on delete cascade
