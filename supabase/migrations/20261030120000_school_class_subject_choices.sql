  (school_id, code, name, is_optional, is_active, sort_order)
select s.id, levels.code, levels.name, levels.is_optional,
  levels.is_active, levels.sort_order
from public.schools s
cross join (values
  ('kg', 'Kindergarten', false, true, 10),
  ('primary_1', 'Primary 1', false, true, 20),
  ('primary_2', 'Primary 2', false, true, 30),
  ('primary_3', 'Primary 3', false, true, 40),
  ('primary_4', 'Primary 4', false, true, 50),
  ('primary_5', 'Primary 5', false, true, 60),
  ('primary_6', 'Primary 6', true, false, 70),
  ('jss_1', 'JSS 1', false, true, 80),
  ('jss_2', 'JSS 2', false, true, 90),
  ('jss_3', 'JSS 3', false, true, 100),
  ('sss_1', 'SSS 1', false, true, 110),
  ('sss_2', 'SSS 2', false, true, 120),
  ('sss_3', 'SSS 3', false, true, 130)
) as levels(code, name, is_optional, is_active, sort_order)
where
  s.school_type = 'Combined'
  or s.school_type = 'Other'
  or (s.school_type = 'Primary' and levels.sort_order < 80)
  or (s.school_type = 'Secondary' and levels.sort_order >= 80)
on conflict (school_id, code) do nothing;

