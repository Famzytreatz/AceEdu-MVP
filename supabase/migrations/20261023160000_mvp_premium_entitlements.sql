create table if not exists public.school_trial_identities (
  id bigint generated by default as identity primary key,
  normalized_registration_id varchar(80) not null unique,
  trial_started_at timestamptz,
  trial_ends_at timestamptz,
  verified_at timestamptz,
  created_at timestamptz not null default now(),
  constraint school_trial_dates_are_paired
    check ((trial_started_at is null) = (trial_ends_at is null)),
  constraint school_trial_dates_are_ordered
    check (trial_ends_at is null or trial_ends_at > trial_started_at)
);

create table if not exists public.platform_operators (
  id bigint generated by default as identity primary key,
  email varchar(254) not null unique,
  password_hash text not null,
  is_active boolean not null default true,
  created_at timestamptz not null default now()
);

create table if not exists public.school_entitlements (
  school_id bigint primary key references public.schools (id) on delete cascade,
  plan varchar(10) not null default 'mvp' check (plan in ('mvp', 'premium')),
  verification_status varchar(20) not null default 'not_requested'
    check (verification_status in ('not_requested', 'pending', 'verified', 'review_required', 'rejected')),
  registration_identity_id bigint references public.school_trial_identities (id) on delete set null,
  updated_at timestamptz not null default now()
);

create table if not exists public.school_verification_requests (
  id bigint generated by default as identity primary key,
  school_id bigint not null references public.schools (id) on delete cascade,
  registration_identity_id bigint not null references public.school_trial_identities (id) on delete restrict,
  school_name varchar(160) not null,
  country varchar(80) not null,
  state varchar(100) not null,
  city varchar(100) not null,
  status varchar(20) not null check (status in ('pending', 'review_required', 'approved', 'rejected')),
  review_reason varchar(40),
  rejection_reason varchar(500),
  reviewed_by bigint references public.platform_operators (id) on delete set null,
  created_at timestamptz not null default now(),
  reviewed_at timestamptz
);

create index if not exists school_verification_queue
  on public.school_verification_requests (status, created_at);

create index if not exists school_verification_identity
  on public.school_verification_requests (registration_identity_id, created_at desc);

create unique index if not exists one_open_school_verification_request
  on public.school_verification_requests (school_id)
  where status in ('pending', 'review_required');

alter table public.school_trial_identities enable row level security;
alter table public.platform_operators enable row level security;
alter table public.school_entitlements enable row level security;
alter table public.school_verification_requests enable row level security;

revoke all on public.school_trial_identities from public, anon, authenticated;
revoke all on public.platform_operators from public, anon, authenticated;
revoke all on public.school_entitlements from public, anon, authenticated;
revoke all on public.school_verification_requests from public, anon, authenticated;

create or replace function public.ensure_school_entitlement()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  insert into public.school_entitlements (school_id)
  values (new.id)
  on conflict (school_id) do nothing;
  return new;
end;
$$;

drop trigger if exists schools_create_default_entitlement on public.schools;
create trigger schools_create_default_entitlement
  after insert on public.schools
  for each row execute function public.ensure_school_entitlement();

insert into public.school_entitlements (school_id)
select id from public.schools
on conflict (school_id) do nothing;

create or replace function public.get_school_entitlement(target_school_id bigint)
returns jsonb
language sql
stable
security invoker
set search_path = public
as $$
  select jsonb_build_object(
    'plan', e.plan,
    'verificationStatus', e.verification_status,
    'trialStartedAt', i.trial_started_at,
    'trialEndsAt', i.trial_ends_at,
    'trialActive', coalesce(i.trial_started_at <= now() and now() < i.trial_ends_at, false),
    'effectivePlan', case
      when e.plan = 'premium' or coalesce(i.trial_started_at <= now() and now() < i.trial_ends_at, false)
        then 'premium'
      else 'mvp'
    end,
    'trialPreviouslyGranted', i.trial_started_at is not null
  )
  from public.school_entitlements e
  left join public.school_trial_identities i on i.id = e.registration_identity_id
  where e.school_id = target_school_id;
$$;

create or replace function public.request_school_verification(
  target_school_id bigint,
  submitted_registration_id text
)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  canonical_id text;
  identity_row public.school_trial_identities%rowtype;
  school_row public.schools%rowtype;
  current_entitlement public.school_entitlements%rowtype;
  request_status text;
  reason text;
  request_row public.school_verification_requests%rowtype;
  linked_elsewhere boolean;
begin
  canonical_id := upper(regexp_replace(trim(submitted_registration_id), '[^[:alnum:]]', '', 'g'));
  if canonical_id is null or length(canonical_id) < 2 or length(canonical_id) > 80 then
    raise exception 'Enter a valid official school registration ID.' using errcode = '22023';
  end if;

  select * into school_row from public.schools where id = target_school_id;
  if not found then
    raise exception 'School account was not found.' using errcode = 'P0002';
  end if;

  insert into public.school_trial_identities (normalized_registration_id)
  values (canonical_id)
  on conflict (normalized_registration_id) do nothing;

  select * into identity_row
  from public.school_trial_identities
  where normalized_registration_id = canonical_id
  for update;

  insert into public.school_entitlements (school_id)
  values (target_school_id)
  on conflict (school_id) do nothing;

  select * into current_entitlement
  from public.school_entitlements
  where school_id = target_school_id
  for update;

  if current_entitlement.registration_identity_id is not null
     and current_entitlement.registration_identity_id <> identity_row.id then
    raise exception 'This school account is already linked to a different registration identity.'
      using errcode = '23505';
  end if;

  select exists (
    select 1 from public.school_entitlements
    where registration_identity_id = identity_row.id and school_id <> target_school_id
  ) into linked_elsewhere;

  if identity_row.trial_started_at is not null then
    request_status := 'review_required';
    reason := 'trial_previously_granted';
  elsif linked_elsewhere then
    request_status := 'review_required';
    reason := 'registration_id_already_linked';
  else
    request_status := 'pending';
    reason := null;
  end if;

  select * into request_row
  from public.school_verification_requests
  where school_id = target_school_id and status in ('pending', 'review_required')
  order by created_at desc
  limit 1;

  if found then
    return jsonb_build_object(
      'id', request_row.id,
      'status', request_row.status,
      'reviewReason', request_row.review_reason
    );
  end if;

  insert into public.school_verification_requests (
    school_id, registration_identity_id, school_name, country, state, city, status, review_reason
  ) values (
    target_school_id, identity_row.id, school_row.school_name, school_row.country,
    school_row.state, school_row.city, request_status, reason
  )
  returning * into request_row;

  update public.school_entitlements
  set registration_identity_id = identity_row.id,
      verification_status = request_status,
      updated_at = now()
  where school_id = target_school_id;

  return jsonb_build_object(
    'id', request_row.id,
    'status', request_row.status,
    'reviewReason', request_row.review_reason
  );
end;
$$;

create or replace function public.approve_school_verification(
  target_request_id bigint,
  target_operator_id bigint
)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  request_row public.school_verification_requests%rowtype;
  identity_row public.school_trial_identities%rowtype;
  start_at timestamptz := now();
begin
  perform 1 from public.platform_operators
  where id = target_operator_id and is_active = true;
  if not found then
    raise exception 'Active platform operator is required.' using errcode = '42501';
  end if;

  select * into request_row
  from public.school_verification_requests
  where id = target_request_id
  for update;
  if not found or request_row.status not in ('pending', 'review_required') then
    raise exception 'Verification request is not available for approval.' using errcode = 'P0002';
  end if;

  select * into identity_row
  from public.school_trial_identities
  where id = request_row.registration_identity_id
  for update;
  if identity_row.trial_started_at is not null then
    raise exception 'A Premium trial has already been granted to this school identity.'
      using errcode = '23505';
  end if;

  perform 1 from public.school_entitlements
  where registration_identity_id = identity_row.id
    and school_id <> request_row.school_id;
  if found then
    raise exception 'This registration identity is already linked to another school.'
      using errcode = '23505';
  end if;

  update public.school_trial_identities
  set trial_started_at = start_at,
      trial_ends_at = start_at + interval '90 days',
      verified_at = start_at
  where id = identity_row.id;

  update public.school_entitlements
  set verification_status = 'verified', updated_at = start_at
  where school_id = request_row.school_id
    and registration_identity_id = identity_row.id;

  update public.school_verification_requests
  set status = 'approved', reviewed_by = target_operator_id, reviewed_at = start_at
  where id = target_request_id;

  return jsonb_build_object(
    'status', 'approved',
    'trialStartedAt', start_at,
    'trialEndsAt', start_at + interval '90 days'
  );
end;
$$;

create or replace function public.reject_school_verification(
  target_request_id bigint,
  target_operator_id bigint,
  rejection_reason text
)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  request_row public.school_verification_requests%rowtype;
  clean_reason text := nullif(trim(rejection_reason), '');
begin
  perform 1 from public.platform_operators
  where id = target_operator_id and is_active = true;
  if not found then
    raise exception 'Active platform operator is required.' using errcode = '42501';
  end if;
  if clean_reason is null or length(clean_reason) > 500 then
    raise exception 'Provide a review reason of 1 to 500 characters.' using errcode = '22023';
  end if;

  select * into request_row
  from public.school_verification_requests
  where id = target_request_id
  for update;
  if not found or request_row.status not in ('pending', 'review_required') then
    raise exception 'Verification request is not available for rejection.' using errcode = 'P0002';
  end if;

  update public.school_verification_requests
  set status = 'rejected',
      rejection_reason = clean_reason,
      reviewed_by = target_operator_id,
      reviewed_at = now()
  where id = target_request_id;

  update public.school_entitlements
  set verification_status = 'rejected', updated_at = now()
  where school_id = request_row.school_id
    and registration_identity_id = request_row.registration_identity_id;

  return jsonb_build_object('status', 'rejected');
end;
$$;

