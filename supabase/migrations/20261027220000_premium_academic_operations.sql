create or replace function public.create_academic_year(
  target_school_id bigint,
  year_name text,
  year_starts_on date,
  year_ends_on date,
  number_of_terms smallint
)
returns jsonb
language plpgsql
security invoker
set search_path = public
as $$
declare
  year_id bigint;
  term_index integer;
  year_days integer;
begin
  if nullif(trim(year_name), '') is null or length(trim(year_name)) > 80 then
    raise exception 'Enter an academic year name of 1 to 80 characters.'
      using errcode = '22023';
  end if;
  if year_starts_on is null or year_ends_on is null or year_ends_on <= year_starts_on then
    raise exception 'The academic year end date must be after its start date.'
      using errcode = '22023';
  end if;
  if number_of_terms is null or number_of_terms < 1 or number_of_terms > 12 then
    raise exception 'Academic years must contain between 1 and 12 terms.'
      using errcode = '22023';
  end if;
  year_days := year_ends_on - year_starts_on + 1;
  if number_of_terms > year_days then
    raise exception 'The academic year must be at least as long as its term count.'
      using errcode = '22023';
  end if;

  insert into public.academic_years (
    school_id, name, starts_on, ends_on, term_count, is_current
  ) values (
    target_school_id, trim(year_name), year_starts_on, year_ends_on,
    number_of_terms, not exists (
      select 1 from public.academic_years where school_id = target_school_id
    )
  )
  returning id into year_id;

  for term_index in 1..number_of_terms loop
    insert into public.academic_terms (
      school_id, academic_year_id, term_number, name, starts_on, ends_on
    ) values (
      target_school_id,
      year_id,
      term_index,
      'Term ' || term_index,
      year_starts_on + floor((year_days::numeric * (term_index - 1)) / number_of_terms)::integer,
      year_starts_on + floor((year_days::numeric * term_index) / number_of_terms)::integer - 1
    );
  end loop;

  return jsonb_build_object('id', year_id, 'termCount', number_of_terms);
end;
$$;

create or replace function public.set_current_academic_year(
  target_school_id bigint,
  target_year_id bigint
)
returns void
language plpgsql
security invoker
set search_path = public
as $$
begin
  perform 1
  from public.academic_years
  where id = target_year_id and school_id = target_school_id
  for update;
  if not found then
    raise exception 'Academic year not found for this school.'
      using errcode = 'P0002';
  end if;

  update public.academic_years
  set is_current = false
  where school_id = target_school_id
    and id <> target_year_id
    and is_current;

  update public.academic_years
  set is_current = true
  where school_id = target_school_id
    and id = target_year_id;
end;
$$;

create or replace function public.assign_school_class(
  target_school_id bigint,
  target_class_id bigint,
  target_student_ids bigint[]
)
returns integer
language plpgsql
security invoker
set search_path = public
as $$
declare
  updated_count integer;
begin
  if cardinality(target_student_ids) > 500 then
    raise exception 'Assign no more than 500 students at a time.'
      using errcode = '22023';
  end if;
  if not exists (
    select 1 from public.school_classes
    where id = target_class_id and school_id = target_school_id
  ) then
    raise exception 'Class not found for this school.' using errcode = 'P0002';
  end if;
  if exists (
    select 1
    from unnest(target_student_ids) as requested(id)
    left join public.enrollments e
      on e.id = requested.id
      and e.school_id = target_school_id
      and e.role = 'student'
      and e.status = 'Active'
    where e.id is null
  ) then
    raise exception 'One or more selected students are not active in this school.'
      using errcode = '22023';
  end if;

  update public.enrollments
  set class_id = null,
      designation = '',
      updated_at = now()
  where school_id = target_school_id
    and role = 'student'
    and class_id = target_class_id
    and not (id = any(target_student_ids));

  update public.enrollments
  set class_id = target_class_id,
      designation = (
        select name from public.school_classes
        where id = target_class_id and school_id = target_school_id
      ),
      updated_at = now()
  where school_id = target_school_id
    and role = 'student'
    and id = any(target_student_ids);
  get diagnostics updated_count = row_count;
  return updated_count;
end;
$$;

