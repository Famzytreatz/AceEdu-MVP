create table if not exists public.school_class_students (
  id bigint generated by default as identity primary key,
  school_id bigint not null references public.schools (id) on delete cascade,
  class_id bigint not null,
  student_id bigint not null,
  created_at timestamptz not null default now(),
  constraint school_class_student_class_school_fk
    foreign key (class_id, school_id)
    references public.school_classes (id, school_id) on delete cascade,
  constraint school_class_student_enrollment_school_fk
    foreign key (student_id, school_id)
    references public.enrollments (id, school_id) on delete cascade,
  constraint school_class_student_unique unique (school_id, class_id, student_id)
);

insert into public.school_class_students (school_id, class_id, student_id)
select e.school_id, e.class_id, e.id
from public.enrollments e
join public.school_classes c
  on c.id = e.class_id and c.school_id = e.school_id
where e.role = 'student'
on conflict (school_id, class_id, student_id) do nothing;

insert into public.school_class_students (school_id, class_id, student_id)
select result.school_id, assessment.class_id, result.student_id
from public.assessment_results result
join public.academic_assessments assessment
  on assessment.id = result.assessment_id
  and assessment.school_id = result.school_id
on conflict (school_id, class_id, student_id) do nothing;

insert into public.school_class_students (school_id, class_id, student_id)
select record.school_id, session.class_id, record.student_id
from public.attendance_records record
join public.attendance_sessions session
  on session.id = record.attendance_session_id
  and session.school_id = record.school_id
on conflict (school_id, class_id, student_id) do nothing;

create index if not exists school_class_students_by_student
  on public.school_class_students (school_id, student_id, class_id);

alter table public.school_class_students enable row level security;
revoke all on public.school_class_students from public, anon, authenticated;
grant all on public.school_class_students to service_role;

create or replace function public.assign_school_class(
  target_school_id bigint,
  target_class_id bigint,
  target_student_ids bigint[]
)
returns integer
language plpgsql
security invoker
set search_path = public
as $$
declare
  target_year_id bigint;
  target_is_current boolean;
  updated_count integer;
begin
  if cardinality(target_student_ids) > 500 then
    raise exception 'Assign no more than 500 students at a time.'
      using errcode = '22023';
  end if;

  select c.academic_year_id, y.is_current
  into target_year_id, target_is_current
  from public.school_classes c
  join public.academic_years y
    on y.id = c.academic_year_id and y.school_id = c.school_id
  where c.id = target_class_id and c.school_id = target_school_id;

  if not found then
    raise exception 'Class not found for this school.' using errcode = 'P0002';
  end if;

  if exists (
    select 1
    from unnest(target_student_ids) as requested(id)
    left join public.enrollments e
      on e.id = requested.id
      and e.school_id = target_school_id
      and e.role = 'student'
    where e.id is null
      or (
        e.status <> 'Active'
        and not exists (
          select 1
          from public.school_class_students roster
          where roster.school_id = target_school_id
            and roster.class_id = target_class_id
            and roster.student_id = requested.id
        )
      )
  ) then
    raise exception 'Selected students must be active in this school.'
      using errcode = '22023';
  end if;

  delete from public.school_class_students roster
  using public.school_classes other_class
  where roster.school_id = target_school_id
    and roster.student_id = any(target_student_ids)
    and roster.class_id = other_class.id
    and other_class.school_id = target_school_id
    and other_class.academic_year_id = target_year_id
    and roster.class_id <> target_class_id;

  delete from public.school_class_students roster
  where roster.school_id = target_school_id
    and roster.class_id = target_class_id
    and not (roster.student_id = any(target_student_ids));

  insert into public.school_class_students (school_id, class_id, student_id)
  select target_school_id, target_class_id, requested.id
  from unnest(target_student_ids) as requested(id)
  on conflict (school_id, class_id, student_id) do nothing;

  if target_is_current then
    update public.enrollments
    set class_id = null,
        designation = '',
        updated_at = now()
    where school_id = target_school_id
      and role = 'student'
      and class_id = target_class_id
      and not (id = any(target_student_ids));

    update public.enrollments
    set class_id = target_class_id,
        designation = (
          select name from public.school_classes
          where id = target_class_id and school_id = target_school_id
        ),
        updated_at = now()
    where school_id = target_school_id
      and role = 'student'
      and status = 'Active'
      and id = any(target_student_ids);
    get diagnostics updated_count = row_count;
  else
    get diagnostics updated_count = row_count;
  end if;

  return updated_count;
end;
$$;

revoke all on function public.assign_school_class(bigint, bigint, bigint[])
  from public, anon, authenticated;
grant execute on function public.assign_school_class(bigint, bigint, bigint[])
  to service_role;
