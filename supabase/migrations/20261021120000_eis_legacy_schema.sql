create table if not exists public.eis_users (
  id bigint generated by default as identity primary key,
  full_name text not null,
  role text not null,
  designation text,
  assigned_classes text,
  subjects text,
  access_pin text not null unique,
  passport text,
  reg_date timestamptz not null default now(),
  status text not null default 'Pending',
  registered_by text not null default 'Staff Terminal',
  dob text,
  guardian_phone text,
  address text,
  state_of_origin text,
  phone text,
  country text,
  region text,
  home_address text,
  password_hash text
);

create index if not exists eis_users_role_designation
  on public.eis_users (role, designation);

create table if not exists public.eis_messages (
  id bigint generated by default as identity primary key,
  target text not null default 'all',
  sender text not null default 'Admin Office',
  content text not null,
  date timestamptz not null default now(),
  priority text not null default 'normal',
  message_type text
);

create index if not exists eis_messages_target_date
  on public.eis_messages (target, date desc);

create table if not exists public.eis_content (
  id bigint generated by default as identity primary key,
  subject text,
  target_class text not null,
  teacher_name text,
  type text not null default 'material',
  title text not null,
  body text,
  content_body text,
  deadline timestamptz,
  file_url text,
  author text,
  created_at timestamptz not null default now()
);

create index if not exists eis_content_target_class_created
  on public.eis_content (target_class, created_at desc);

create table if not exists public.eis_exams (
  id bigint generated by default as identity primary key,
  teacher_id text not null,
  target_class text not null,
  title text not null,
  questions jsonb not null default '[]'::jsonb,
  duration_minutes integer not null check (duration_minutes > 0),
  attempts_allowed integer not null default 1 check (attempts_allowed > 0),
  created_at timestamptz not null default now(),
  expires_at timestamptz not null
);

create index if not exists eis_exams_class_created
  on public.eis_exams (target_class, created_at desc);

create index if not exists eis_exams_teacher_created
  on public.eis_exams (teacher_id, created_at desc);

create table if not exists public.eis_exam_attempts (
  id bigint generated by default as identity primary key,
  student_id text not null,
  exam_id bigint not null references public.eis_exams (id) on delete cascade,
  class_id text not null,
  attempt_number integer not null default 1 check (attempt_number > 0),
  start_time timestamptz,
  end_time timestamptz,
  answers jsonb not null default '[]'::jsonb,
  score integer,
  status text not null default 'started'
    check (status in ('started', 'submitted', 'expired', 'revoked')),
  is_revoked boolean not null default false,
  submission_type text not null default 'manual'
);

create index if not exists eis_exam_attempts_student_exam
  on public.eis_exam_attempts (student_id, exam_id);

create index if not exists eis_exam_attempts_exam_score
  on public.eis_exam_attempts (exam_id, score desc);

alter table public.eis_users enable row level security;
alter table public.eis_messages enable row level security;
alter table public.eis_content enable row level security;
alter table public.eis_exams enable row level security;
alter table public.eis_exam_attempts enable row level security;
