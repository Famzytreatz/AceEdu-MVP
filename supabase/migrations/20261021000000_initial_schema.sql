create table if not exists public.schools (
  id bigint generated by default as identity primary key,
  school_name varchar(160) not null,
  school_type varchar(40) not null check (school_type in ('Nursery/Primary', 'Secondary', 'Combined', 'Other')),
  country varchar(80) not null,
  state varchar(100) not null,
  city varchar(100) not null,
  address varchar(300) not null,
  school_email varchar(254) not null,
  school_phone varchar(30) not null,
  admin_name varchar(160) not null,
  admin_email varchar(254) not null unique,
  admin_phone varchar(30) not null,
  admin_role varchar(40) not null check (admin_role in ('Proprietor', 'Principal', 'School Administrator', 'Other')),
  password_hash text not null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index if not exists schools_by_creation
  on public.schools (created_at desc, id desc);

create table if not exists public.enrollments (
  id bigint generated by default as identity primary key,
  school_id bigint not null references public.schools (id) on delete cascade,
  full_name varchar(160) not null,
  name_search text generated always as (lower(full_name)) stored,
  role varchar(20) not null check (role in ('student', 'teacher', 'sub-admin', 'school-admin')),
  designation varchar(120) not null,
  access_pin varchar(6) not null check (access_pin ~ '^[0-9]{6}$'),
  status varchar(7) not null default 'Pending' check (status in ('Pending', 'Active')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint unique_school_access_pin unique (school_id, access_pin)
);

create index if not exists school_enrollment_page
  on public.enrollments (school_id, id desc);

create index if not exists school_enrollment_name
  on public.enrollments (school_id, name_search text_pattern_ops);

create index if not exists school_enrollment_pin
  on public.enrollments (school_id, access_pin text_pattern_ops);

create table if not exists public.sessions (
  sid text primary key,
  sess jsonb not null,
  expire timestamptz not null
);

create index if not exists sessions_expire
  on public.sessions (expire);

alter table public.schools enable row level security;
alter table public.enrollments enable row level security;
alter table public.sessions enable row level security;
