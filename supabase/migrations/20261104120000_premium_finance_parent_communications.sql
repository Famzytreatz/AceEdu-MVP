create or replace function public.create_school_parent_account(
  target_school_id bigint,
  parent_name text,
  parent_phone text,
  parent_password_hash text,
  linked_student_ids jsonb
)
returns bigint
language plpgsql
security invoker
set search_path = public
as $$
declare
  new_parent_id bigint;
  requested_count integer;
  valid_count integer;
begin
  if linked_student_ids is null or jsonb_typeof(linked_student_ids) <> 'array'
    or jsonb_array_length(linked_student_ids) < 1
    or jsonb_array_length(linked_student_ids) > 20 then
    raise exception 'Link one to 20 students.' using errcode = '22023';
  end if;

  select count(*), count(distinct student.value::bigint)
    into requested_count, valid_count
  from jsonb_array_elements_text(linked_student_ids) as student(value);
  if requested_count <> valid_count then
    raise exception 'Student links must be unique.' using errcode = '22023';
  end if;

  select count(*) into valid_count
  from public.enrollments e
  join jsonb_array_elements_text(linked_student_ids) as student(value)
    on e.id = student.value::bigint
  where e.school_id = target_school_id
    and e.role = 'student'
    and e.status = 'Active';
  if valid_count <> requested_count then
    raise exception 'Every linked student must be active in this school.'
      using errcode = '22023';
  end if;

  insert into public.parent_accounts (
    school_id, full_name, phone, password_hash
  ) values (
    target_school_id, trim(parent_name), parent_phone, parent_password_hash
  )
  returning id into new_parent_id;

  insert into public.parent_student_links (
    school_id, parent_id, student_id, relationship
  )
  select target_school_id, new_parent_id, student.value::bigint, 'guardian'
  from jsonb_array_elements_text(linked_student_ids) as student(value);

  return new_parent_id;
end;
$$;

create or replace function public.set_school_parent_students(
  target_school_id bigint,
  target_parent_id bigint,
  linked_student_ids jsonb
)
returns integer
language plpgsql
security invoker
set search_path = public
as $$
declare
  requested_count integer;
  valid_count integer;
begin
  if linked_student_ids is null or jsonb_typeof(linked_student_ids) <> 'array'
    or jsonb_array_length(linked_student_ids) < 1
    or jsonb_array_length(linked_student_ids) > 20 then
    raise exception 'Link one to 20 students.' using errcode = '22023';
  end if;

  if not exists (
    select 1 from public.parent_accounts
    where id = target_parent_id and school_id = target_school_id
      and is_active
  ) then
    raise exception 'Parent account not found for this school.'
      using errcode = 'P0002';
  end if;

  select count(*), count(distinct student.value::bigint)
    into requested_count, valid_count
  from jsonb_array_elements_text(linked_student_ids) as student(value);
  if requested_count <> valid_count then
    raise exception 'Student links must be unique.' using errcode = '22023';
  end if;

  select count(*) into valid_count
  from public.enrollments e
  join jsonb_array_elements_text(linked_student_ids) as student(value)
    on e.id = student.value::bigint
  where e.school_id = target_school_id
    and e.role = 'student'
    and e.status = 'Active';
  if valid_count <> requested_count then
    raise exception 'Every linked student must be active in this school.'
      using errcode = '22023';
  end if;

  delete from public.parent_student_links
  where school_id = target_school_id and parent_id = target_parent_id;
  insert into public.parent_student_links (
    school_id, parent_id, student_id, relationship
  )
  select target_school_id, target_parent_id, student.value::bigint, 'guardian'
  from jsonb_array_elements_text(linked_student_ids) as student(value);

  return requested_count;
end;
$$;

create or replace function public.record_school_fee_payment(
  target_school_id bigint,
  target_fee_account_id bigint,
  payment_amount numeric,
  payment_type text,
  payment_reference text,
  payment_date date
)
returns jsonb
language plpgsql
security invoker
set search_path = public
as $$
declare
  amount_due numeric(14, 2);
  already_paid numeric(14, 2);
  payment_id bigint;
  remaining numeric(14, 2);
begin
  if payment_amount is null or payment_amount <= 0
    or payment_amount > 1000000000
    or payment_amount <> round(payment_amount, 2) then
    raise exception 'Payment amount must be positive with up to two decimals.'
      using errcode = '22023';
  end if;
  if payment_type not in ('cash', 'bank_transfer', 'cheque', 'other') then
    raise exception 'Choose a valid manual payment method.' using errcode = '22023';
  end if;
  if length(coalesce(payment_reference, '')) > 100 then
    raise exception 'Payment reference is too long.' using errcode = '22023';
  end if;

  select account.amount_due into amount_due
  from public.student_fee_accounts account
  where account.id = target_fee_account_id
    and account.school_id = target_school_id
  for update;
  if not found then
    raise exception 'Student fee account not found for this school.' using errcode = 'P0002';
  end if;

  select coalesce(sum(amount), 0) into already_paid
  from public.student_fee_payments
  where fee_account_id = target_fee_account_id and school_id = target_school_id;
  remaining := amount_due - already_paid;
  if payment_amount > remaining then
    raise exception 'Payment exceeds the invoice balance.' using errcode = '22023';
  end if;

  insert into public.student_fee_payments (
    school_id, fee_account_id, amount, method, reference, payment_date
  ) values (
    target_school_id, target_fee_account_id, payment_amount, payment_type,
    nullif(trim(payment_reference), ''), coalesce(payment_date, current_date)
  )
  returning id into payment_id;

  return jsonb_build_object(
    'id', payment_id,
    'feeAccountId', target_fee_account_id,
    'amount', payment_amount,
    'method', payment_type,
    'reference', nullif(trim(payment_reference), ''),
    'paidOn', coalesce(payment_date, current_date),
    'balance', remaining - payment_amount
  );
end;
$$;

